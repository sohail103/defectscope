"""Project discovery: language detection, roles, build systems, exclusions."""
from __future__ import annotations

import fnmatch
import os
from collections import Counter, defaultdict
from pathlib import Path

from ..core.schemas import ExclusionRules, FileInfo

PY_EXT = {".py"}
C_EXT = {".c"}
CPP_EXT = {".cpp", ".cc", ".cxx", ".c++", ".hpp", ".hh", ".hxx", ".h++"}
H_EXT = {".h"}  # ambiguous: C or C++

BUILD_FILES = {
    "CMakeLists.txt": "CMake", "Makefile": "Make", "makefile": "Make", "meson.build": "Meson",
    "configure.ac": "Autotools", "setup.py": "setuptools", "pyproject.toml": "pyproject",
    "setup.cfg": "setuptools", "requirements.txt": "pip requirements", "tox.ini": "tox",
    "BUILD": "Bazel", "BUILD.bazel": "Bazel", "WORKSPACE": "Bazel", "compile_commands.json": "compile_commands",
    "SConstruct": "SCons", "Pipfile": "pipenv", "poetry.lock": "poetry",
}
TEST_DIRS = {"test", "tests", "testing", "unittests", "__tests__", "spec", "specs"}
GENERATED_MARKERS = (b"generated by", b"do not edit", b"autogenerated", b"auto-generated", b"@generated")
GENERATED_NAME_PATTERNS = ("*_pb2.py", "*_pb2_grpc.py", "*.pb.cc", "*.pb.h", "moc_*.cpp", "*.generated.*")


def _is_binary(chunk: bytes) -> bool:
    return b"\x00" in chunk


def _role(rel: str, ext: str, name: str) -> str:
    parts = rel.lower().split("/")
    lname = name.lower()
    if any(p in TEST_DIRS for p in parts[:-1]) or lname.startswith("test_") or \
            lname.rsplit(".", 1)[0].endswith(("_test", "_tests")):
        return "test"
    if name in BUILD_FILES:
        return "build"
    if ext in H_EXT or ext in {".hpp", ".hh", ".hxx", ".h++"}:
        return "header"
    if ext in PY_EXT | C_EXT | CPP_EXT:
        return "source"
    if ext in {".json", ".yml", ".yaml", ".toml", ".ini", ".cfg"}:
        return "config"
    return "other"


def discover(root: Path, rules: ExclusionRules) -> tuple[list[FileInfo], dict]:
    """Walk `root` applying exclusion rules. Returns (files, summary)."""
    files: list[FileInfo] = []
    tmp_lang: dict[str, str | None] = {}
    excluded_dirs: dict[str, str] = {}
    build_systems: dict[str, list[str]] = defaultdict(list)
    has_git = (root / ".git").exists()
    vendored = {d.lower() for d in rules.vendored_dirs}
    skip_dirs = {d.lower() for d in rules.dirs}

    for dirpath, dirnames, filenames in os.walk(root):
        rel_dir = os.path.relpath(dirpath, root).replace(os.sep, "/")
        rel_dir = "" if rel_dir == "." else rel_dir
        keep = []
        for d in sorted(dirnames):
            rel = f"{rel_dir}/{d}" if rel_dir else d
            full = Path(dirpath) / d
            if full.is_symlink():
                excluded_dirs[rel] = "symlink"
            elif d.lower() in skip_dirs or d.endswith(".egg-info"):
                excluded_dirs[rel] = "excluded directory"
            elif rules.exclude_vendored and d.lower() in vendored:
                excluded_dirs[rel] = "vendored dependency"
            elif any(fnmatch.fnmatch(rel, g) for g in rules.extra_globs):
                excluded_dirs[rel] = "custom exclusion"
            else:
                keep.append(d)
        dirnames[:] = keep

        for fn in sorted(filenames):
            full = Path(dirpath) / fn
            rel = f"{rel_dir}/{fn}" if rel_dir else fn
            if full.is_symlink():
                continue
            try:
                size = full.stat().st_size
            except OSError:
                continue
            ext = os.path.splitext(fn)[1].lower()
            lang = "python" if ext in PY_EXT else "c" if ext in C_EXT else "cpp" if ext in CPP_EXT else \
                "h" if ext in H_EXT else None
            info = FileInfo(path=rel, size=size, role=_role(rel, ext, fn))
            if fn in BUILD_FILES:
                build_systems[BUILD_FILES[fn]].append(rel)
            tmp_lang[rel] = lang  # resolved below once the project mix is known
            files.append(info)

    has_cpp = "cpp" in tmp_lang.values()
    has_c = "c" in tmp_lang.values()
    for f in files:
        tmp = tmp_lang.get(f.path)
        if tmp == "h":
            # Headers are ambiguous. C++ is a superset for parsing purposes, so use it
            # whenever the project contains any C++ sources; otherwise assume C.
            f.language = "cpp" if has_cpp else "c"
        elif tmp:
            f.language = tmp

        if f.language is None:
            continue
        name = f.path.rsplit("/", 1)[-1]
        if f.size > rules.max_file_bytes:
            f.excluded, f.exclusion_reason = True, f"larger than {rules.max_file_bytes // 1024} KB"
        elif rules.exclude_tests and f.role == "test":
            f.excluded, f.exclusion_reason = True, "test file"
        elif any(fnmatch.fnmatch(f.path, g) or fnmatch.fnmatch(name, g) for g in rules.extra_globs):
            f.excluded, f.exclusion_reason = True, "custom exclusion"
        elif rules.exclude_generated and any(fnmatch.fnmatch(name, g) for g in GENERATED_NAME_PATTERNS):
            f.excluded, f.exclusion_reason = True, "generated code"
        else:
            try:
                with open(root / f.path, "rb") as fh:
                    head = fh.read(8192)
            except OSError:
                f.excluded, f.exclusion_reason = True, "unreadable"
                continue
            if _is_binary(head):
                f.excluded, f.exclusion_reason = True, "binary"
            elif rules.exclude_generated and any(m in head[:1024].lower() for m in GENERATED_MARKERS):
                f.excluded, f.exclusion_reason = True, "generated code"

    return files, _summarise(files, excluded_dirs, build_systems, has_git, has_c, has_cpp)


def _summarise(files, excluded_dirs, build_systems, has_git, has_c, has_cpp) -> dict:
    lang_files: Counter = Counter()
    lang_bytes: Counter = Counter()
    excl_reasons: Counter = Counter()
    src_dirs: Counter = Counter()
    test_dirs: set[str] = set()
    for f in files:
        if f.language is None:
            continue
        if f.excluded:
            excl_reasons[f.exclusion_reason or "excluded"] += 1
            continue
        lang_files[f.language] += 1
        lang_bytes[f.language] += f.size
        d = f.path.rsplit("/", 1)[0] if "/" in f.path else "."
        (test_dirs.add(d) if f.role == "test" else src_dirs.update([d]))
    for reason in excluded_dirs.values():
        excl_reasons[f"dir: {reason}"] += 1

    roots = sorted({p.rsplit("/", 1)[0] if "/" in p else "." for ps in build_systems.values() for p in ps})
    return {
        "languages": {k: {"files": lang_files[k], "bytes": lang_bytes[k]} for k in lang_files},
        "analysable_files": sum(lang_files.values()),
        "excluded_files": sum(1 for f in files if f.excluded),
        "excluded_directories": excluded_dirs,
        "exclusion_reasons": dict(excl_reasons),
        "build_systems": {k: v for k, v in build_systems.items()},
        "has_compile_commands": "compile_commands" in build_systems,
        "project_roots": roots,
        "source_directories": [d for d, _ in src_dirs.most_common(15)],
        "test_directories": sorted(test_dirs)[:15],
        "has_git": has_git,
        "mixed_language": len(lang_files) > 1,
        "header_language_assumption": (
            "C++" if has_cpp else "C" if has_c else None
        ),
        "total_files": len(files),
        "total_bytes": sum(f.size for f in files),
    }
